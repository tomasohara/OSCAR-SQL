/*
 * Get the database connection from DatabaseManager
 *
 * Returns: QSqlDatabase instance
 */
QSqlDatabase MachineRepository::database()
{
    return DatabaseManager::instance().database();
}

/*
 * Create a new machine in the database
 *
 * Parameters:
 *   data - MachineData containing machine information
 *
 * Returns: Machine database ID if successful, -1 on error
 *
 * The id field in data is ignored (auto-generated by database).
 * The createdAt timestamp is set automatically by the database.
 */
qint64 MachineRepository::create(const MachineData& data)
{
    QSqlQuery query(database());
    
    query.prepare(
        "INSERT INTO machines ("
        "profile_id, machine_id, loader_name, machine_type, "
        "brand, model, series, serial_number, model_number, "
        "last_imported, purge_date, data_version, properties"
        ") VALUES ("
        ":profile_id, :machine_id, :loader_name, :machine_type, "
        ":brand, :model, :series, :serial_number, :model_number, "
        ":last_imported, :purge_date, :data_version, :properties"
        ")"
    );
    
    query.bindValue(":profile_id", data.profileId);
    query.bindValue(":machine_id", data.machineId);
    query.bindValue(":loader_name", data.loaderName);
    query.bindValue(":machine_type", data.machineType);
    query.bindValue(":brand", data.brand);
    query.bindValue(":model", data.model);
    query.bindValue(":series", data.series);
    query.bindValue(":serial_number", data.serialNumber);
    query.bindValue(":model_number", data.modelNumber);
    query.bindValue(":last_imported", data.lastImported);
    query.bindValue(":purge_date", data.purgeDate);
    query.bindValue(":data_version", data.dataVersion);
    query.bindValue(":properties", data.properties);
    
    if (!query.exec()) {
        qWarning() << "MachineRepository::create() failed:" << query.lastError().text();
        return -1;
    }
    
    qint64 id = query.lastInsertId().toLongLong();
    qDebug() << "MachineRepository: Created machine" << data.brand << data.model 
             << "serial" << data.serialNumber << "with id" << id;
    
    return id;
}

/*
 * Find a machine by database ID
 *
 * Parameters:
 *   id - Database primary key
 *
 * Returns: MachineData if found, or null MachineData (id=0) if not found
 */
MachineData MachineRepository::findById(qint64 id)
{
    QSqlQuery query(database());
    
    query.prepare(
        "SELECT id, profile_id, machine_id, loader_name, machine_type, "
        "brand, model, series, serial_number, model_number, "
        "last_imported, purge_date, data_version, properties, created_at "
        "FROM machines WHERE id = :id"
    );
    
    query.bindValue(":id", id);
    
    if (!query.exec()) {
        qWarning() << "MachineRepository::findById() failed:" << query.lastError().text();
        return MachineData();
    }
    
    if (query.next()) {
        return recordToData(query);
    }
    
    return MachineData();
}

